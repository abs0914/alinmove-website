export function phoneHref(phone: string): string {
  const digits = phone.replace(/\D/g, "");
  if (digits.startsWith("63")) return `tel:+${digits}`;
  if (digits.startsWith("0")) return `tel:+63${digits.slice(1)}`;
  return `tel:+63${digits}`;
}

export function directionsHref(branchLocation: BranchSummary): string {
  const destination = `${branchLocation.latitude},${branchLocation.longitude}`;
  return `https://www.google.com/maps/dir/?api=1&destination=${encodeURIComponent(destination)}`;
}

export function haversineKm(a: Coordinates, b: Coordinates): number {
  const radians = (degrees: number) => (degrees * Math.PI) / 180;
  const earthRadiusKm = 6371;
  const latitudeDelta = radians(b.latitude - a.latitude);
  const longitudeDelta = radians(b.longitude - a.longitude);
  const firstLatitude = radians(a.latitude);
  const secondLatitude = radians(b.latitude);
  const value =
    Math.sin(latitudeDelta / 2) ** 2 +
    Math.cos(firstLatitude) * Math.cos(secondLatitude) * Math.sin(longitudeDelta / 2) ** 2;
  return earthRadiusKm * 2 * Math.atan2(Math.sqrt(value), Math.sqrt(1 - value));
}

export function findNearestPickupBranch(
  origin: Coordinates,
  branches: readonly BranchSummary[] = BRANCHES,
): { branch: BranchSummary; directDistanceKm: number } | null {
  return (
    branches
      .filter((item) => item.isActive && item.acceptsPickupToBranch)
      .map((item) => ({
        branch: item,
        directDistanceKm: haversineKm(origin, {
          latitude: item.latitude,
          longitude: item.longitude,
        }),
      }))
      .sort((a, b) => a.directDistanceKm - b.directDistanceKm)[0] || null
  );
}
